import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const scope={URL,document:{baseURI:'https://example.com/page'}};
vm.runInNewContext(fs.readFileSync(new URL('../Extension/video-source.js',import.meta.url),'utf8'),scope);
const video=(src,other={})=>({currentSrc:src,src:'',mediaKeys:null,querySelector:()=>null,...other});
const {resolve,filename}=scope.SwiftDownloadVideo;
assert.equal(resolve(video('https://mp4.vjshi.com/sample.mp4?token=123')).format,'MP4');
assert.equal(resolve(video('/sample.webm')).url,'https://example.com/sample.webm');
assert.ok(resolve(video('blob:https://example.com/id')).error);
assert.ok(resolve(video('https://example.com/video.m3u8?token=abc')).error);
assert.ok(resolve(video('https://example.com/video.mpd')).error);
assert.ok(resolve(video('file:///etc/passwd')).error);
assert.ok(resolve(video('https://user:pass@example.com/file.mp4')).error);
assert.ok(resolve(video('https://example.com/file.mp4',{mediaKeys:{}})).error);
assert.ok(resolve(video('')).error);
assert.equal(resolve(video('',{querySelector:()=>({src:'https://example.com/fallback.mp4'})})).ext,'mp4');
assert.equal(filename('../../A/B:demo','mp4'),'.._.._A_B_demo.mp4');
assert.ok(filename('x'.repeat(200),'webm').length<=105);
console.log('PASS video URL selection, direct MP4/WebM, relative paths, DRM/blob/playlist rejection and safe filename');

assert.equal(scope.SwiftDownloadVideo.formatSize(8126464),'7.75 MB');
assert.equal(scope.SwiftDownloadVideo.formatSize(20706050),'19.75 MB');
assert.equal(scope.SwiftDownloadVideo.formatSize(null),'大小未知');
assert.equal(scope.SwiftDownloadVideo.formatSize(-1),'大小未知');
console.log('PASS byte sizes and unknown size display');
assert.equal(resolve(video('blob:https://www.youtube.com/id'),'https://www.youtube.com/watch?v=BaW_jenozKc&list=unrelated').url,'https://www.youtube.com/watch?v=BaW_jenozKc');
assert.equal(resolve(video('blob:https://www.youtube.com/id'),'https://www.youtube.com/shorts/BaW_jenozKc').youtube,true);
assert.ok(resolve(video('blob:https://evil.example/id'),'https://youtube.com.evil.example/watch?v=BaW_jenozKc').error);
assert.ok(resolve(video('blob:https://www.youtube.com/id',{mediaKeys:{}}),'https://www.youtube.com/watch?v=BaW_jenozKc').error);
console.log('PASS YouTube canonical single-video selection and DRM/host boundary');
let callback;
const expired={Map,Element:class {},chrome:{get runtime(){throw new Error('Extension context invalidated')}},document:{documentElement:{}},MutationObserver:class {observe(){}},addEventListener(){},requestAnimationFrame(fn){callback=fn}};
vm.runInNewContext(fs.readFileSync(new URL('../Extension/video.js',import.meta.url),'utf8'),expired);
assert.doesNotThrow(()=>callback());
console.log('PASS reloaded extension context stops without uncaught error');
